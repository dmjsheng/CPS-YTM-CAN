static StatusTypeDef OLED_I2C_Transmit(uint8_t *pData, uint16_t Size)
{
    if (s_i2c_oled.State != I2C_STATE_READY)
    {
        /* 自动恢复 I2C 外设状态，防止单次总线扰动使驱动永久锁死在 I2C_STATE_ERROR */
        I2C_Stop_Config(&s_i2c_oled, ENABLE);
        s_i2c_oled.State = I2C_STATE_READY;
    }
    StatusTypeDef status = I2C_Master_Transmit(&s_i2c_oled, OLED_I2C_ADDR, pData, Size);
    if (status != STATUS_OK)
    {
        I2C_Stop_Config(&s_i2c_oled, ENABLE);
        s_i2c_oled.State = I2C_STATE_READY;
    }
    return status;
}

static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2];
    buf[0] = 0x00u;
    buf[1] = cmd;
    OLED_I2C_Transmit(buf, 2);
}

static void __attribute__((unused)) OLED_WriteData(uint8_t dat)
{
    uint8_t buf[2];
    buf[0] = 0x40u;
    buf[1] = dat;
    OLED_I2C_Transmit(buf, 2);
}

void OLED_SetPos(uint8_t x, uint8_t page)
{
    OLED_WriteCmd(0xB0u + page);
    OLED_WriteCmd(((x & 0xF0u) >> 4) | 0x10u);
    OLED_WriteCmd(x & 0x0Fu);
}

void OLED_Clear(void)
{
    uint8_t page, col;
    uint8_t buf[17];
    buf[0] = 0x40u;
    memset(&buf[1], 0x00, 16);

    for (page = 0; page < 8; page++)
    {
        OLED_SetPos(0, page);
        for (col = 0; col < 8; col++)
        {
            I2C_Master_Transmit(&s_i2c_oled, OLED_I2C_ADDR, buf, 17);
        }
    }
}

void Init_OLED(void)
{
    GPIO_InitTypeDef GPIO_InitStruct;
    cps_ddl_memclr(&GPIO_InitStruct, sizeof(GPIO_InitStruct));

    /* 开启 GPIOA 和 I2C0 时钟 */
    RCC_AHBPeriphClockCmd(RCC, RCC_AHBPeriph_GPIOA_CKEN, ENABLE);
    RCC_APBPeriphClockCmd(RCC, RCC_APBPeriph_I2C0_CKEN, ENABLE);

    /* 配置 PA11 (SCL) 和 PA10 (SDA) */
    GPIO_InitStruct.GPIO_Pin = GPIO_Pin_10 | GPIO_Pin_11;
    GPIO_InitStruct.GPIO_Mode = GPIO_Mode_OUT;
    GPIO_InitStruct.GPIO_OType = GPIO_OType_OD;
    GPIO_InitStruct.GPIO_PuPd = GPIO_PuPd_UP;
    GPIO_Init(GPIOA, &GPIO_InitStruct);

    GPIO_PinAFConfig(GPIOA, GPIO_PinSource11, GPIO_AF_I2C0_SCL_PA11);
    GPIO_PinAFConfig(GPIOA, GPIO_PinSource10, GPIO_AF_I2C0_SDA_PA10);

    /* I2C0 主机模式配置 (400kHz) */
    s_i2c_oled.Instance = I2C0;
    s_i2c_oled.Init.master = I2C_MASTER_MODE_ENABLE;
    s_i2c_oled.Init.slave = I2C_SLAVE_MODE_DISABLE;
    s_i2c_oled.Mode = I2C_MODE_MASTER;
    s_i2c_oled.Init.broadack = I2C_BROAD_ACK_DISABLE;
    s_i2c_oled.Init.speedclock = 400; /* 400kHz */
    s_i2c_oled.State = I2C_STATE_RESET;
    I2C_Init(&s_i2c_oled);

    /* SSD1306 初始化序列 */
    OLED_WriteCmd(0xAE); /* 关闭显示 */
    OLED_WriteCmd(0xD5); /* 设置分频系数/时钟 */
    OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8); /* 设置多路复用数 (64行) */
    OLED_WriteCmd(0x3F);
    OLED_WriteCmd(0xD3); /* 设置显示偏移 */
    OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40); /* 设置起始行 */
    OLED_WriteCmd(0x8D); /* 电荷泵使能 */
    OLED_WriteCmd(0x14);
    OLED_WriteCmd(0x20); /* 内存寻址模式: 页寻址 */
    OLED_WriteCmd(0x02);
    OLED_WriteCmd(0xA1); /* 段重映射 A0/A1 */
    OLED_WriteCmd(0xC8); /* COM输出扫描方向 C0/C8 */
    OLED_WriteCmd(0xDA); /* COM硬件引脚配置 */
    OLED_WriteCmd(0x12);
    OLED_WriteCmd(0x81); /* 对比度控制 */
    OLED_WriteCmd(0xCF);
    OLED_WriteCmd(0xD9); /* 预充电周期 */
    OLED_WriteCmd(0xF1);
    OLED_WriteCmd(0xDB); /* VCOMH反压检测 */
    OLED_WriteCmd(0x30);
    OLED_WriteCmd(0xA4); /* 全局显示开启 A4正常/A5全亮 */
    OLED_WriteCmd(0xA6); /* 正显 A6/反显 A7 */
    OLED_WriteCmd(0xAF); /* 开启显示 */

    OLED_Clear();
}

void OLED_ShowChar(uint8_t x, uint8_t line, char ch)
{
    uint8_t c = (uint8_t)ch - ' ';
    uint8_t buf[9];
    buf[0] = 0x40u;

    if (c >= sizeof(OLED_F8x16) / 16)
    {
        return;
    }

    /* 上半部分 8x8 (page = line) */
    OLED_SetPos(x, line);
    memcpy(&buf[1], &OLED_F8x16[c][0], 8);
    OLED_I2C_Transmit(buf, 9);

    /* 下半部分 8x8 (page = line + 1) */
    OLED_SetPos(x, line + 1);
    memcpy(&buf[1], &OLED_F8x16[c][8], 8);
    OLED_I2C_Transmit(buf, 9);
}

void OLED_ShowString(uint8_t x, uint8_t line, const char *str)
{
    uint8_t len = 0;
    const char *p = str;
    while (*p && (x + len * 8 <= 128))
    {
        len++;
        p++;
    }
    if (len == 0) return;

    /* 块传输：一整行上半部分一次 I2C 连续发完，极大降低 I2C 启停与仲裁开销 */
    uint8_t buf[1 + 16 * 8];
    buf[0] = 0x40u;
    for (uint8_t i = 0; i < len; i++)
    {
        uint8_t c = (uint8_t)str[i] - ' ';
        if (c >= sizeof(OLED_F8x16) / 16) c = 0;
        memcpy(&buf[1 + i * 8], &OLED_F8x16[c][0], 8);
    }
    OLED_SetPos(x, line);
    OLED_I2C_Transmit(buf, 1 + len * 8);

    /* 块传输：一整行下半部分一次 I2C 连续发完 */
    for (uint8_t i = 0; i < len; i++)
    {
        uint8_t c = (uint8_t)str[i] - ' ';
        if (c >= sizeof(OLED_F8x16) / 16) c = 0;
        memcpy(&buf[1 + i * 8], &OLED_F8x16[c][8], 8);
    }
    OLED_SetPos(x, line + 1);
    OLED_I2C_Transmit(buf, 1 + len * 8);
}

void OLED_ShowHex8(uint8_t x, uint8_t line, uint8_t val)
{
    const char hex_chars[] = "0123456789ABCDEF";
    OLED_ShowChar(x, line, hex_chars[(val >> 4) & 0x0F]);
    OLED_ShowChar(x + 8, line, hex_chars[val & 0x0F]);
}

void OLED_ShowHex16(uint8_t x, uint8_t line, uint16_t val)
{
    OLED_ShowHex8(x, line, (uint8_t)(val >> 8));
    OLED_ShowHex8(x + 16, line, (uint8_t)(val & 0xFF));
}

void OLED_ShowDec(uint8_t x, uint8_t line, uint32_t val, uint8_t len)
{
    char str[12];
    str[len] = '\0';
    for (int8_t i = len - 1; i >= 0; i--)
    {
        str[i] = (char)('0' + (val % 10));
        val /= 10;
    }
    OLED_ShowString(x, line, str);
}
